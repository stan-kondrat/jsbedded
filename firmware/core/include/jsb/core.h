/* Engine-neutral runtime entry point, called by the platform after reset. */
#ifndef JSB_CORE_H
#define JSB_CORE_H

#include <stddef.h>
#include <stdint.h>

#include "jsb/engine.h"

/* Run the firmware main loop; never returns. */
void jsb_main(void) __attribute__((noreturn));

/* --- timers (src/timers.c) --- */

/* Define setTimeout, setInterval, clearTimeout, clearInterval. Returns 0 or -1. */
int jsb_timers_install(jsb_engine *engine);

/* Run every timer that is due, earliest first; callbacks' exceptions are logged. */
void jsb_timers_run_due(jsb_engine *engine);

/* Milliseconds until the next timer is due (0 if one is due now), or -1 if none is pending. */
int64_t jsb_timers_next_wait(void);

/* --- board (src/board.c) --- */

/* Define the global `board`: name, and LED where the board has a simple one. Returns 0 or -1. */
int jsb_board_install(jsb_engine *engine);

/* --- boot script (generated by core.cmake from SCRIPT=, default core/boot.js) --- */

extern const unsigned char jsb_script[]; /* NUL-terminated */
extern const size_t jsb_script_len;
extern const char jsb_script_name[];

#endif
